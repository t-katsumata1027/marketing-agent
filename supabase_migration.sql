-- SKIP LOCKED により複数 publisher が同じ approved 投稿を確保できない。
CREATE OR REPLACE FUNCTION public.claim_posts_for_publish(p_limit INTEGER, p_lease_seconds INTEGER)
RETURNS SETOF public.posts_log LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE item public.posts_log;
BEGIN
  -- X 呼出し前に停止した lease だけは安全に再確保できる。送信開始済みは絶対に回収しない。
  UPDATE public.posts_log SET status='approved', publish_lease_token=NULL,
    publish_lease_expires_at=NULL, last_error='lease_expired_before_dispatch', updated_at=now()
  WHERE status='publishing' AND publish_dispatch_started_at IS NULL
    AND publish_lease_expires_at <= now();
  FOR item IN SELECT * FROM public.posts_log WHERE status = 'approved' ORDER BY created_at FOR UPDATE SKIP LOCKED LIMIT p_limit LOOP
    UPDATE public.posts_log SET status='publishing', publish_lease_token=gen_random_uuid(),
      publish_lease_expires_at=now()+make_interval(secs => p_lease_seconds), retry_count=retry_count+1,
      last_error=NULL, updated_at=now() WHERE id=item.id RETURNING * INTO item;
    RETURN NEXT item;
  END LOOP;
END; $$;

CREATE OR REPLACE FUNCTION public.claim_mentions_for_reply(p_project_name TEXT, p_limit INTEGER, p_lease_seconds INTEGER)
RETURNS SETOF public.mentions_log LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE item public.mentions_log; BEGIN
 UPDATE public.mentions_log SET status='unprocessed', processing_lease_token=NULL, processing_lease_expires_at=NULL WHERE status='processing' AND processing_lease_expires_at <= now();
 FOR item IN SELECT * FROM public.mentions_log WHERE project_name=p_project_name AND status='unprocessed' ORDER BY created_at FOR UPDATE SKIP LOCKED LIMIT p_limit LOOP
  UPDATE public.mentions_log SET status='processing', processing_lease_token=gen_random_uuid(), processing_lease_expires_at=now()+make_interval(secs=>p_lease_seconds), retry_count=retry_count+1 WHERE id=item.id RETURNING * INTO item; RETURN NEXT item;
 END LOOP; END; $$;
