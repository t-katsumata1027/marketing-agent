CREATE OR REPLACE FUNCTION public.recover_failed_post(
  p_post_id BIGINT, p_operator_note TEXT, p_confirmed_not_published BOOLEAN
) RETURNS SETOF public.posts_log LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE item public.posts_log;
BEGIN
  IF NOT p_confirmed_not_published OR length(btrim(coalesce(p_operator_note, ''))) < 8 THEN
    RAISE EXCEPTION 'operator_confirmation_and_note_are_required' USING ERRCODE='P0001';
  END IF;
  SELECT * INTO item FROM public.posts_log WHERE id=p_post_id FOR UPDATE;
  IF NOT FOUND OR item.status <> 'failed' OR item.x_tweet_id IS NOT NULL OR item.publish_dispatch_started_at IS NOT NULL THEN
    RAISE EXCEPTION 'post_is_not_safe_to_recover' USING ERRCODE='P0001';
  END IF;
  UPDATE public.posts_log SET status='draft', last_error=NULL, publish_lease_token=NULL,
    publish_lease_expires_at=NULL WHERE id=p_post_id RETURNING * INTO item;
  INSERT INTO public.operations_audit_log(entity_type, entity_id, action, operator_note)
    VALUES ('post', p_post_id, 'recover_failed_to_draft', left(p_operator_note, 2000));
  RETURN NEXT item;
END; $$;

-- 送信開始済みは自動復旧しない。retry 上限到達後の未送信投稿・メンションは
-- failed として運用者に可視化し、無限再試行を防止する。
CREATE OR REPLACE FUNCTION public.claim_posts_for_publish(p_limit INTEGER, p_lease_seconds INTEGER)
RETURNS SETOF public.posts_log LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE item public.posts_log;
BEGIN
  IF p_limit NOT BETWEEN 1 AND 100 OR p_lease_seconds NOT BETWEEN 30 AND 3600 THEN
    RAISE EXCEPTION 'invalid_claim_parameters' USING ERRCODE='22023';
  END IF;
  UPDATE public.posts_log SET status='failed', last_error='retry_limit_exceeded_before_dispatch', publish_lease_token=NULL, publish_lease_expires_at=NULL
    WHERE status='publishing' AND publish_dispatch_started_at IS NULL AND publish_lease_expires_at <= now() AND retry_count >= 5;
  UPDATE public.posts_log SET status='approved', publish_lease_token=NULL, publish_lease_expires_at=NULL, last_error='lease_expired_before_dispatch'
    WHERE status='publishing' AND publish_dispatch_started_at IS NULL AND publish_lease_expires_at <= now() AND retry_count < 5;
  FOR item IN SELECT * FROM public.posts_log WHERE status='approved' AND retry_count < 5 ORDER BY created_at FOR UPDATE SKIP LOCKED LIMIT p_limit LOOP
    UPDATE public.posts_log SET status='publishing', publish_lease_token=gen_random_uuid(), publish_lease_expires_at=now()+make_interval(secs=>p_lease_seconds), retry_count=retry_count+1, last_error=NULL WHERE id=item.id RETURNING * INTO item;
    RETURN NEXT item;
  END LOOP;
END; $$;

CREATE OR REPLACE FUNCTION public.claim_mentions_for_reply(p_project_name TEXT, p_limit INTEGER, p_lease_seconds INTEGER)
RETURNS SETOF public.mentions_log LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE item public.mentions_log;
BEGIN
  IF length(btrim(coalesce(p_project_name, ''))) = 0 OR p_limit NOT BETWEEN 1 AND 100 OR p_lease_seconds NOT BETWEEN 30 AND 3600 THEN
    RAISE EXCEPTION 'invalid_claim_parameters' USING ERRCODE='22023';
  END IF;
  UPDATE public.mentions_log SET status='failed', last_error='retry_limit_exceeded', processing_lease_token=NULL, processing_lease_expires_at=NULL
    WHERE status='processing' AND processing_lease_expires_at <= now() AND retry_count >= 5;
  UPDATE public.mentions_log SET status='unprocessed', processing_lease_token=NULL, processing_lease_expires_at=NULL
    WHERE status='processing' AND processing_lease_expires_at <= now() AND retry_count < 5;
  FOR item IN SELECT * FROM public.mentions_log WHERE project_name=p_project_name AND status='unprocessed' AND retry_count < 5 ORDER BY created_at FOR UPDATE SKIP LOCKED LIMIT p_limit LOOP
    UPDATE public.mentions_log SET status='processing', processing_lease_token=gen_random_uuid(), processing_lease_expires_at=now()+make_interval(secs=>p_lease_seconds), retry_count=retry_count+1 WHERE id=item.id RETURNING * INTO item;
    RETURN NEXT item;
  END LOOP;
END; $$;

