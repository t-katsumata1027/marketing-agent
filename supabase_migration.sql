-- トークン照合・一回消費・draft→approved を一つのトランザクションで実行する。
CREATE OR REPLACE FUNCTION public.approve_post_with_token(p_token_hash TEXT, p_ip_hash TEXT DEFAULT NULL, p_user_agent_hash TEXT DEFAULT NULL)
RETURNS BIGINT LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE token_row public.post_approval_tokens; approved_id BIGINT;
BEGIN
  SELECT * INTO token_row FROM public.post_approval_tokens WHERE token_hash=p_token_hash FOR UPDATE;
  IF NOT FOUND OR token_row.used_at IS NOT NULL OR token_row.revoked_at IS NOT NULL OR token_row.expires_at <= now() THEN
    RAISE EXCEPTION 'invalid_or_expired_approval_token' USING ERRCODE='P0001';
  END IF;
  UPDATE public.posts_log SET status='approved', updated_at=now() WHERE id=token_row.post_id AND status='draft' RETURNING id INTO approved_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'post_is_not_draft' USING ERRCODE='P0001'; END IF;
  UPDATE public.post_approval_tokens SET used_at=now(), used_by_ip_hash=p_ip_hash, user_agent_hash=p_user_agent_hash WHERE id=token_row.id;
  RETURN approved_id;
END; $$;

