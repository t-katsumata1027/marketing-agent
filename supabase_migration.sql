DROP FUNCTION IF EXISTS public.claim_scheduled_job(TEXT, TEXT, INTEGER, INTEGER);
CREATE FUNCTION public.claim_scheduled_job(p_project_name TEXT,p_job_name TEXT,p_interval_seconds INTEGER,p_lease_seconds INTEGER) RETURNS UUID LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE claimed_token UUID;
BEGIN
  IF length(btrim(coalesce(p_project_name, ''))) = 0 OR length(btrim(coalesce(p_job_name, ''))) = 0 OR p_interval_seconds NOT BETWEEN 1 AND 2592000 OR p_lease_seconds NOT BETWEEN 30 AND 3600 THEN
    RAISE EXCEPTION 'invalid_scheduled_job_parameters' USING ERRCODE='22023';
  END IF;
  INSERT INTO public.scheduled_job_runs(project_name,job_name) VALUES(p_project_name,p_job_name) ON CONFLICT DO NOTHING;
  UPDATE public.scheduled_job_runs SET status='running', lease_token=gen_random_uuid(), lease_expires_at=now()+make_interval(secs=>p_lease_seconds), updated_at=now()
   WHERE project_name=p_project_name AND job_name=p_job_name
     AND (lease_expires_at IS NULL OR lease_expires_at<=now())
     AND (last_success_at IS NULL OR last_success_at<=now()-make_interval(secs=>p_interval_seconds))
  RETURNING lease_token INTO claimed_token;
  RETURN claimed_token;
END; $$;
DROP FUNCTION IF EXISTS public.finish_scheduled_job(TEXT, TEXT, BOOLEAN, TEXT);
CREATE FUNCTION public.finish_scheduled_job(p_project_name TEXT,p_job_name TEXT,p_lease_token UUID,p_success BOOLEAN,p_error TEXT) RETURNS BOOLEAN LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE affected_rows INTEGER;
BEGIN
  UPDATE public.scheduled_job_runs SET status=CASE WHEN p_success THEN 'idle' ELSE 'failed' END,
    last_success_at=CASE WHEN p_success THEN now() ELSE last_success_at END,
    last_error=CASE WHEN p_success THEN NULL ELSE p_error END, lease_expires_at=NULL, lease_token=NULL,
    retry_count=CASE WHEN p_success THEN retry_count ELSE retry_count+1 END, updated_at=now()
  WHERE project_name=p_project_name AND job_name=p_job_name AND status='running' AND lease_token=p_lease_token;
  GET DIAGNOSTICS affected_rows = ROW_COUNT;
  RETURN affected_rows = 1;
END; $$;

