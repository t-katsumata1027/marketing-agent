CREATE OR REPLACE FUNCTION public.enforce_post_state_transition() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NEW.status <> OLD.status AND NOT (
    (OLD.status='draft' AND NEW.status='approved') OR
    (OLD.status='approved' AND NEW.status='publishing') OR
    (OLD.status='publishing' AND NEW.status IN ('approved','published','failed')) OR
    (OLD.status='failed' AND NEW.status='draft')
  ) THEN
    RAISE EXCEPTION 'invalid_post_state_transition: % -> %', OLD.status, NEW.status USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END; $$;
CREATE OR REPLACE FUNCTION public.enforce_mention_state_transition() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NEW.status <> OLD.status AND NOT (
    (OLD.status='unprocessed' AND NEW.status='processing') OR
    (OLD.status='processing' AND NEW.status IN ('unprocessed','processed','failed'))
  ) THEN
    RAISE EXCEPTION 'invalid_mention_state_transition: % -> %', OLD.status, NEW.status USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END; $$;
CREATE OR REPLACE FUNCTION public.enforce_job_state_transition() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NEW.status <> OLD.status AND NOT (
    (OLD.status IN ('idle','failed') AND NEW.status='running') OR
    (OLD.status='running' AND NEW.status IN ('idle','failed'))
  ) THEN
    RAISE EXCEPTION 'invalid_job_state_transition: % -> %', OLD.status, NEW.status USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END; $$;
